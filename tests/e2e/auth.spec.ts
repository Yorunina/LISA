test('network failure leaves credentials editable and retry possible', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('用户名', { exact: true }).fill('offline_reader')
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.route('**/api/auth/login', route => route.abort())
  await page.getByRole('button', { name: '进入书房', exact: true }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page.getByLabel('密码', { exact: true })).toHaveValue(password)
  await expect(page.getByRole('button', { name: '进入书房', exact: true })).toBeEnabled()
  await page.unroute('**/api/auth/login')
  const response = page.waitForResponse('**/api/auth/login')
  await page.getByRole('button', { name: '进入书房', exact: true }).click()
  expect((await response).status()).toBe(401)
  await expect(page.getByRole('alert')).toBeVisible()
})
