import { expect, test } from '@playwright/test'

const password = 'synthetic-password-2026'
const headers = { 'X-LISA-Request': '1' }

test('binding confirmation and explicit persona editing preserve saved state', async ({ page }, testInfo) => {
  await page.goto('/')
  await page.getByRole('button', { name: '使用邀请码注册' }).click()
  await page.getByLabel('用户名', { exact: true }).fill('setup_reader')
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.getByLabel('邀请码', { exact: true }).fill(process.env.LISA_TEST_INVITES!.split(',')[2])
  await page.getByRole('button', { name: '创建账号并进入书房' }).click()
  await page.getByLabel('绑定码', { exact: true }).fill('invalid-binding-code')
  await page.getByRole('button', { name: '核对 QQ 号' }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page.getByLabel('绑定码', { exact: true })).toHaveValue('invalid-binding-code')
  await page.getByLabel('绑定码', { exact: true }).fill(process.env.LISA_TEST_BINDING_CODE!)
  await page.getByRole('button', { name: '核对 QQ 号' }).click()
  await expect(page.locator('.qq-number')).toHaveText('700000001')
  expect((await (await page.request.get('/api/setup')).json()).qq_id).toBeNull()
  await page.screenshot({ path: testInfo.outputPath('binding-confirmation.png'), fullPage: true })
  await page.getByRole('button', { name: '确认绑定', exact: true }).click()
  await page.getByLabel('性格名称', { exact: true }).fill('窗边的小莎')
  await page.getByLabel('核心性格与价值倾向', { exact: true }).fill('合成测试：平和交流，尊重用户的创作意见。')
  await page.getByLabel('虚拟身份与生活背景', { exact: true }).fill('合成虚拟背景，不是生活事实。')
  expect((await (await page.request.get('/api/setup')).json()).persona).toBeNull()
  await page.getByLabel('核心性格与价值倾向', { exact: true }).press('Control+s')
  await expect(page.getByText('初始化已完成', { exact: true })).toBeVisible()
  await expect(page.getByText('已保存', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '返回书房', exact: true }).click()
  await page.getByRole('button', { name: '调整 LISA 性格' }).click()
  await expect(page.getByLabel('核心性格与价值倾向', { exact: true })).toHaveValue('合成测试：平和交流，尊重用户的创作意见。')
  await page.getByText('原有文字与补充说明', { exact: true }).click()
  const revisedPrompt = '合成测试：修改后的性格继续保留共同经历。'
  await page.getByLabel('LISA 性格 prompt', { exact: true }).fill(revisedPrompt)
  await page.getByRole('button', { name: '返回书房', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '有未保存的性格修改' })
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: '继续编辑' }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByLabel('LISA 性格 prompt', { exact: true })).toHaveValue(revisedPrompt)
  await page.route('**/api/setup/persona', route => route.abort())
  await page.getByRole('button', { name: '返回书房', exact: true }).click()
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page.getByLabel('LISA 性格 prompt', { exact: true })).toHaveValue(revisedPrompt)
  await page.unroute('**/api/setup/persona')
  await page.getByRole('button', { name: '返回书房', exact: true }).click()
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await page.getByRole('button', { name: '调整 LISA 性格' }).click()
  await expect(page.getByLabel('LISA 性格 prompt', { exact: true })).toHaveValue(revisedPrompt)
  expect((await (await page.request.get('/api/setup')).json()).persona.version).toBe(2)
  await page.screenshot({ path: testInfo.outputPath('desktop-persona.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('mobile-persona.png'), fullPage: true })
  await page.getByLabel('LISA 性格 prompt', { exact: true }).fill('不会保存的合成修改')
  await page.getByRole('button', { name: '返回书房', exact: true }).click()
  await page.screenshot({ path: testInfo.outputPath('mobile-unsaved-dialog.png') })
  await dialog.getByRole('button', { name: '放弃修改' }).click()
  await page.getByRole('button', { name: '调整 LISA 性格' }).click()
  await expect(page.getByLabel('LISA 性格 prompt', { exact: true })).toHaveValue(revisedPrompt)
})

test('QQ recovery resets the password, expires old sessions and retains persona', async ({ page, browser }, testInfo) => {
  const oldSession = await browser.newContext({ baseURL: process.env.LISA_TEST_BASE_URL })
  try {
    expect((await oldSession.request.post('/api/auth/login', {
      data: { username: 'recovery_reader', password }, headers,
    })).status()).toBe(200)
    await page.goto('/')
    await page.getByRole('button', { name: '忘记用户名或密码' }).click()
    await page.getByLabel('找回码', { exact: true }).fill('invalid-recovery-code')
    await page.getByRole('button', { name: '验证找回码' }).click()
    await expect(page.getByRole('alert')).toBeVisible()
    await expect(page.getByLabel('找回码', { exact: true })).toHaveValue('invalid-recovery-code')
    await page.getByLabel('找回码', { exact: true }).fill(process.env.LISA_TEST_RECOVERY_CODE!)
    await page.getByRole('button', { name: '验证找回码' }).click()
    await expect(page.getByText('recovery_reader', { exact: true })).toBeVisible()
    await page.screenshot({ path: testInfo.outputPath('desktop-recovery.png'), fullPage: true })
    await page.setViewportSize({ width: 390, height: 844 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath('mobile-recovery.png'), fullPage: true })
    await page.getByLabel('新密码', { exact: true }).fill('replacement-password-2026')
    await page.getByRole('button', { name: '设置新密码' }).click()
    await expect(page.getByRole('status')).toContainText('密码已重设')
    expect((await oldSession.request.get('/api/auth/me')).status()).toBe(401)
    await page.getByRole('button', { name: '返回登录', exact: true }).click()
    await page.getByLabel('用户名', { exact: true }).fill('recovery_reader')
    await page.getByLabel('密码', { exact: true }).fill('replacement-password-2026')
    await page.getByRole('button', { name: '进入书房', exact: true }).click()
    await expect(page.getByRole('heading', { name: '我的作品', exact: true })).toBeVisible()
    await page.reload()
    await expect(page.getByRole('heading', { name: '我的作品', exact: true })).toBeVisible()
    await page.getByRole('button', { name: '个人设置', exact: true }).click()
    await expect(page.getByRole('heading', { name: '欢迎，recovery_reader。' })).toBeVisible()
    await expect(page.getByRole('heading', { name: '留存的小莎' })).toBeVisible()
    const setup = await (await page.request.get('/api/setup')).json()
    expect(setup.initialized).toBe(true)
    expect(setup.persona.version).toBe(1)
    expect(setup.persona.prompt).toBe('合成测试：找回账号后保留这份性格。')
  } finally {
    await oldSession.close()
  }
})
